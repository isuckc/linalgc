#!/usr/bin/env python3
"""
Deterministic single-header amalgamator for linalgc -> linalg.h.

Reads modular headers under include/linalg/ in strict dependency order,
strips internal `#include "la_*.h"` directives, and writes a portable,
standalone C99+ / C++17+ linalg.h at the repository root.
"""

from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "include" / "linalg"
OUT_FILE = ROOT / "linalg.h"

MODULES = [
    "la_config.h",
    "la_types.h",
    "la_scalar.h",
    "la_simd.h",
    "la_vec.h",
    "la_mat.h",
    "la_quat.h",
    "la_geom.h",
    "la_batch.h",
    "la_physics.h",
    "la_cpp.h",
]

INTERNAL_INCLUDE_RE = re.compile(r'^\s*#\s*include\s+"la_[a-z0-9_]+\.h"\s*$')

BANNER = """\
/*
 * linalg.h - High-performance Data-Oriented Linear Algebra Library (C99+ / C++17+)
 *
 * SINGLE-HEADER AMALGAMATION (auto-generated by scripts/amalgamate.py)
 * Do not edit this file directly; edit headers under include/linalg/ and run:
 *   make amalgamate
 *
 * Features:
 *   - C99+ and C++17+ compatible, zero heap allocations, strict-aliasing clean
 *   - SIMD backends: ARM64 NEON, x86-64 SSE2/SSE4.1/AVX2+FMA, WASM SIMD128, Scalar
 *   - Column-major matrices (GLSL / Vulkan / Metal / WGSL ready without transpose)
 *   - Explicit RH/LH and [0,1] (ZO) / [-1,1] (NO) / Reverse-Z projection builders
 *   - Data-Oriented SoA & AoSoA4/8 batch kernels (transforms, physics, broadphase, LBS4)
 *   - Physics solvers: inertia tensors, 3x3 Jacobi eigensolver, polar decomp, Cholesky, LDL^T, PGS LCP
 *
 * Configuration macros (define before including linalg.h):
 *   #define LA_FORCE_SCALAR 1     Force pure C99 scalar fallback
 *   #define LA_SEPARATE_IMPL      Emit declarations only for batch/solver kernels;
 *                                 define LINALG_IMPLEMENTATION in one TU for definitions
 *   #define LA_NO_CPP             Disable C++17 namespace la and operators
 *   #define LA_NO_CPP_OPERATORS   Disable C++17 arithmetic operator overloads
 *   #define LA_NO_FORCE_INLINE    Use plain static inline instead of always_inline
 */

#ifndef LINALG_H
#define LINALG_H
"""


def amalgamate() -> None:
    parts = [BANNER]
    for mod in MODULES:
        path = SRC_DIR / mod
        if not path.is_file():
            sys.stderr.write(f"error: missing module {path}\n")
            sys.exit(1)

        raw_lines = path.read_text(encoding="utf-8").splitlines()
        cleaned = []
        for line in raw_lines:
            if INTERNAL_INCLUDE_RE.match(line):
                continue
            cleaned.append(line)

        section_header = (
            f"\n/* ============================================================================\n"
            f" * BEGIN MODULE: {mod}\n"
            f" * ============================================================================ */\n"
        )
        parts.append(section_header)
        parts.append("\n".join(cleaned).strip() + "\n")

    parts.append("\n#endif /* LINALG_H */\n")
    output = "\n".join(parts)

    # Sanity check: ensure no internal includes leaked
    for idx, line in enumerate(output.splitlines(), start=1):
        if INTERNAL_INCLUDE_RE.match(line):
            sys.stderr.write(f"error: internal include leaked at line {idx}: {line}\n")
            sys.exit(1)

    OUT_FILE.write_text(output, encoding="utf-8")
    print(f"Generated {OUT_FILE.relative_to(ROOT)} ({len(output.splitlines())} lines, {len(MODULES)} modules)")


if __name__ == "__main__":
    amalgamate()
